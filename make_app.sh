#!/bin/bash
# Build "Pocket Recordings.app", a launcher for the web app, so it can be
# opened from Launchpad, Spotlight or the Dock.
#
#   ./make_app.sh                 # installs into ~/Applications
#   ./make_app.sh /Applications   # or another folder
#
# Opening the app starts `uv run app.py` in the background (if it isn't
# already running) and opens http://localhost:8765 in your browser. Use the
# Quit button in the web page to stop the server. The app has no Dock icon
# of its own. Logs: ~/Library/Logs/Pocket Recordings.log
#
# The app declares Bluetooth and removable-volume usage, so macOS asks once
# for permission. That's what lets Sync work without starting from Terminal.
# Rebuild after moving this folder (the app records its path).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
DEST="${1:-$HOME/Applications}"
APP="$DEST/Pocket Recordings.app"
BUNDLE_ID="local.pocket-sync.recordings"
UV="$(command -v uv || echo /opt/homebrew/bin/uv)"

if [ -d "$APP" ]; then
  existing=$(/usr/libexec/PlistBuddy -c "Print :CFBundleIdentifier" "$APP/Contents/Info.plist" 2>/dev/null || true)
  if [ "$existing" != "$BUNDLE_ID" ]; then
    echo "Refusing to replace $APP: it isn't one this script built." >&2
    exit 1
  fi
  rm -rf "$APP"
fi
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Pocket Recordings</string>
  <key>CFBundleDisplayName</key><string>Pocket Recordings</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>LSUIElement</key><true/>
  <key>NSBluetoothAlwaysUsageDescription</key>
  <string>Pocket Recordings connects to your Pocket recorder over Bluetooth to list and download recordings.</string>
  <key>NSRemovableVolumesUsageDescription</key>
  <string>Pocket Recordings copies recordings from the Pocket recorder when it is connected by USB.</string>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/launch" <<LAUNCH
#!/bin/bash
# Generated by make_app.sh: starts the Pocket Recordings server and opens it.
export PATH="/opt/homebrew/bin:/usr/local/bin:\$HOME/.local/bin:/usr/bin:/bin:/usr/sbin:/sbin"
PROJECT="$HERE"
UV="$UV"
PORT="\${POCKET_APP_PORT:-8765}"
URL="http://localhost:\$PORT"
LOG="\$HOME/Library/Logs/Pocket Recordings.log"

alert() { osascript -e "display alert \"Pocket Recordings\" message \"\$1\"" >/dev/null 2>&1; }
up() { curl -s -m 1 -o /dev/null "\$URL/api/jobs"; }

if ! up; then
  cd "\$PROJECT" 2>/dev/null || { alert "Project folder not found: \$PROJECT. Rebuild the app with make_app.sh."; exit 1; }
  echo "=== \$(date '+%Y-%m-%d %H:%M:%S') starting" >> "\$LOG"
  nohup "\$UV" run app.py >> "\$LOG" 2>&1 &
  for _ in \$(seq 1 240); do up && break; sleep 0.5; done
  up || { alert "The server didn't start. See \$LOG"; exit 1; }
fi
open "\$URL"
LAUNCH
chmod +x "$APP/Contents/MacOS/launch"

# Icon (drawn with Swift; skipped, leaving the generic app icon, if Swift
# isn't available, e.g. without the Xcode Command Line Tools).
tmp=$(mktemp -d)
if command -v swift >/dev/null 2>&1 && swift "$HERE/tools/make_icon.swift" "$tmp/icon.png" 2>/dev/null; then
  mkdir "$tmp/AppIcon.iconset"
  for s in 16 32 128 256 512; do
    sips -z $s $s "$tmp/icon.png" --out "$tmp/AppIcon.iconset/icon_${s}x${s}.png" >/dev/null
    sips -z $((s * 2)) $((s * 2)) "$tmp/icon.png" --out "$tmp/AppIcon.iconset/icon_${s}x${s}@2x.png" >/dev/null
  done
  iconutil -c icns "$tmp/AppIcon.iconset" -o "$APP/Contents/Resources/AppIcon.icns"
else
  echo "Note: Swift not available; the app gets the generic icon." >&2
fi
rm -rf "$tmp"

# Ad-hoc signature, so macOS can remember the Bluetooth permission.
codesign --force --sign - "$APP" >/dev/null 2>&1
touch "$APP"
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" >/dev/null 2>&1 || true
echo "Built $APP"
